"""A clearly labelled generated demonstration for Waveform Diagnostics.

It renders a plot image of a simulated shot whose front resistor network is 18 %
below nominal, with the label "GENERATED DEMONSTRATION — not a laboratory record"
drawn into the image. The stand-in "true" generator is the same lumped circuit, so
the demonstration shows the workflow, not real-machine accuracy.
"""
import uuid

import numpy as np

from .. import storage
from ..physics.circuit import simulate
from . import VERSION, render
from .reference import snapshot_from_run, as_fired

DEMO_STOCK = {'front': [{'ohm': 30, 'count_per_stage': 1}, {'ohm': 465, 'count_per_stage': 1}],
              'tail': [{'ohm': 520, 'count_per_stage': 1}],
              'provenance': 'Demonstration assumption: one unit per value per stage (not a laboratory inventory)'}
DEMO_REQUEST = dict(profile_id='cpri_problem_brief_profile', impulse_type='Lightning', test_kv=1425, solver='circuit',
                    model_mode='physics', include_base_c=True, load_c_pf=650, divider_c_pf=250, stray_c_pf=55, l_uh=12,
                    efficiency=.83, inventory_override=DEMO_STOCK, layout_id='demo-layout')
TRUE_FRONT_FACTOR = .82


def create_demo():
    from ..optimization.engine import optimize
    from ..schemas import OptimizeRequest
    from .api import _store_bytes, advance
    from . import imaging
    result = optimize(OptimizeRequest.model_validate(DEMO_REQUEST))
    run_id = uuid.uuid4().hex[:12]
    result['run_id'] = run_id
    result['demonstration'] = 'Generated for the Waveform Diagnostics demonstration.'
    run = storage.put('run', run_id, result)
    snap = snapshot_from_run(run)
    fired = as_fired(snap, {'stages': snap['settings']['stages'], 'charge_kv_stage': snap['settings']['charge_kv_stage']})
    reference = storage.put('diagnostic_reference', uuid.uuid4().hex[:12], {**snap, 'as_fired': fired,
                            'revision_note': 'Demonstration reference with as-fired settings recorded'})
    args = dict(fired['prediction']['circuit_args'])
    args['front_r_stage'] *= TRUE_FRONT_FACTOR
    shot = simulate(*args.values(), 'Lightning', True)
    t = np.asarray(shot['waveform']['time_us']); v = np.asarray(shot['waveform']['voltage_kv'])
    keep = t <= 60
    png, truth = render.render_plot([{'t': np.r_[-1, 0, t[keep]], 'v': np.r_[0, 0, v[keep]], 'color': '#1d4ed8', 'width': 1.4}],
                                    time_range=(-1, 60), voltage_range=(-100, 1600), size=(1600, 900), dpi=100,
                                    ticks={'x': list(range(0, 61, 10)), 'y': list(range(0, 1601, 200))})
    sid = uuid.uuid4().hex[:12]
    info = imaging.inspect(png)
    digest, path = _store_bytes(sid, png, 'png')
    storage.put('diagnostic', f'{sid}.0001', {'session_id': sid, 'revision': 1, 'demo': True,
                'title': 'Generated demonstration — front network 18% low', 'reference_id': reference['id'],
                'upload_id': None, 'digitization_id': None, 'comparison_id': None, 'investigation_id': None,
                'note': 'Demonstration reference created', 'version': VERSION})
    x0, t0, x1, t1 = truth['x']; y0, v0, y1, v1 = truth['y']
    upload = storage.put('diagnostic_upload', uuid.uuid4().hex[:12], {
        'origin': 'demonstration', 'origin_label': 'Demonstration (generated)', 'source': 'image', 'image': info,
        'sha256': digest, 'stored_path': path, 'bytes': len(png), 'original_filename': 'generated_demonstration.png',
        'captured_at': None, 'instrument': None, 'session_label': 'Demonstration', 'shot_label': '1', 'notes': None,
        'expected_polarity': 'positive', 'evidence_class': 'image_digitized', 'label': 'Digitized from image — approximate',
        'origin_scope': 'Generated by the application from the same lumped circuit with the front resistance multiplied by '
                        f'{TRUE_FRONT_FACTOR}. It demonstrates the workflow; it is not a laboratory record.',
        'demo_hints': {'plot_box': truth['plot_box'], 'seed_time_us': 20.,
                       'seed_px': list(render.pixel_of(truth, 20., float(np.interp(20., t, v)))),
                       'axes': {'mode': 'anchors', 'time_unit': 'us', 'voltage_unit': 'kV', 'voltage_side': 'high_voltage',
                                'divider_ratio': 1, 'anchor_uncertainty_px': 1,
                                'x_anchors': [{'px': render.pixel_of(truth, 0, 0)[0], 'value': 0}, {'px': render.pixel_of(truth, 60, 0)[0], 'value': 60}],
                                'y_anchors': [{'px': render.pixel_of(truth, 0, 0)[1], 'value': 0}, {'px': render.pixel_of(truth, 0, 1600)[1], 'value': 1600}]},
                       'note': 'Exact axis positions known from the rendering, offered to speed up the demonstration. Confirm them.'},
        'admission': 'Image-derived samples never enter calibration, parameter fitting or laboratory-accuracy workflows.'})
    advance(sid, 'Demonstration image attached', upload_id=upload['id'])
    return sid
